/**
 * Recovery-key setup / rotation modal (see "Encryption" in
 * docs/security.md).
 *
 * Shows the high-entropy recovery key once, in grouped form. Rendering the
 * modal never touches the clipboard (a silent write pushes a
 * 128-bit unlocker into the OS clipboard, clipboard managers, and
 * cloud/universal clipboards without the user choosing it); a "Copy
 * recovery key" button is the only clipboard write site, and it reports its
 * result — success or failure — through a polite live region. The Continue
 * button stays disabled until the user ticks "I have saved my recovery
 * key" — losing every unwrapper makes encrypted data unrecoverable (no
 * operator escrow), so the saved-key confirmation is a hard gate.
 *
 * Built on the shared {@link Modal} (React Aria `Dialog`): the
 * dialog role, focus trap + restore, and Esc/scrim dismiss come from there.
 * The agreement checkbox is a React Aria `Checkbox` (checkbox semantics
 * for agreement, not the on/off `ToggleSwitch`; see "Form controls" in
 * docs/ui-conventions.md).
 */
import React, { useEffect, useRef, useState } from 'react';
import { Checkbox } from 'react-aria-components';
import { Alert } from './Alert';
import { Modal } from './Modal';
import { Muted } from './Muted';
import { btnPrimaryClass, btnSecondaryClass } from './dialog-chrome';

interface RecoveryKeyModalProps {
  /** The raw recovery key to display (already generated by the caller). */
  recoveryKey: string;
  /** Called when the user confirms they've saved the key and continues. */
  onConfirmed: () => void;
  /** Called when the user dismisses without continuing (Esc / scrim / Cancel). */
  onDismiss: () => void;
  /**
   * Optional copy/behaviour overrides for the recovery-key **regeneration** flow
   * (Settings → Security → "Recovery key & encryption"). All default to the first-time-setup
   * presentation, so the setup caller (LoginPage) is unaffected.
   */
  /** Dialog title. Default: "Save your recovery key". */
  title?: string;
  /** Lead paragraph above the key. Default: the setup "only way back" copy. */
  intro?: React.ReactNode;
  /** Warning Alert body below the key. Default: the setup "we can't recover it" copy. */
  warning?: React.ReactNode;
  /** Saved-key confirmation checkbox label. Default: "I have saved my recovery key". */
  savedLabel?: string;
  /** Primary button label. Default: "Continue". */
  confirmLabel?: string;
  /** When set, disables the primary button (e.g. an in-flight activation). */
  confirmDisabled?: boolean;
  /** Optional inline error (e.g. an activation that failed), shown as an Alert. */
  error?: React.ReactNode;
  /**
   * Whether scrim click / Esc dismiss the modal. Defaults to `true` (first-time
   * setup keeps its dismissable behavior). The regeneration flow passes `false`
   * to LOCK the modal: the freshly-minted key can never be re-shown, so a stray
   * outside-click must not discard it — the explicit Cancel button routes
   * through a "Cancel without activating?" confirm instead.
   */
  dismissable?: boolean;
}

/**
 * Copy text to the clipboard. Returns `true` only on a real success.
 * `navigator.clipboard` is absent in insecure contexts / older jsdom, and an
 * optional-chained `await navigator.clipboard?.writeText(...)` would resolve
 * `undefined` without throwing — falsely signalling a copy. Guard the API
 * explicitly so the caller can show the right state. Never throws.
 */
async function copyToClipboard(text: string): Promise<boolean> {
  if (!navigator.clipboard) return false;
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    return false;
  }
}

export const RecoveryKeyModal: React.FC<RecoveryKeyModalProps> = ({
  recoveryKey,
  onConfirmed,
  onDismiss,
  title = 'Save your recovery key',
  intro,
  warning,
  savedLabel = 'I have saved my recovery key',
  confirmLabel = 'Continue',
  confirmDisabled = false,
  error,
  dismissable = true,
}) => {
  const [saved, setSaved] = useState(false);
  // Three outcomes, not a boolean: a denied or unavailable clipboard is a
  // real, user-visible failure now that the write only ever happens from
  // this explicit action — silence would leave the user believing the key
  // landed on the clipboard when it didn't.
  const [copyResult, setCopyResult] = useState<'idle' | 'copied' | 'failed'>(
    'idle',
  );

  // Auto-reset handle for the copy feedback, mirroring
  // SyncDetailsPopover's onCopy/copyState. Stored in a ref so a modal
  // unmount (both consumers unmount this modal on confirm and on cancel)
  // cancels the pending reset instead of setting state on a dead component.
  const copyResetRef = useRef<ReturnType<typeof setTimeout> | null>(null);
  useEffect(() => {
    return () => {
      if (copyResetRef.current !== null) clearTimeout(copyResetRef.current);
    };
  }, []);

  const onCopyClick = async (): Promise<void> => {
    const ok = await copyToClipboard(recoveryKey);
    if (copyResetRef.current !== null) clearTimeout(copyResetRef.current);
    if (ok) {
      setCopyResult('copied');
      // Only the success message is transient. The failure message carries
      // the user's only recovery instruction ("copy the key above
      // manually") — expiring it after 2s would leave a user who glanced
      // away, or who switched apps to paste, back at a modal indistinguishable
      // from one where copy was never pressed. It stays until the user
      // retries (which clears this timeout and sets a fresh result above) or
      // dismisses the modal.
      copyResetRef.current = setTimeout(() => setCopyResult('idle'), 2000);
    } else {
      setCopyResult('failed');
    }
  };

  return (
    <Modal open onClose={onDismiss} title={title} size="md" dismissable={dismissable}>
      <p className="mt-0 text-sm text-ink">
        {intro ?? (
          <>
            This recovery key is the only way back into your encrypted data if you
            ever forget your password. Forgetting your password alone is enough to
            need it. Store it somewhere safe, separate from your password; a
            password manager is ideal.
          </>
        )}
      </p>
      {error && (
        <Alert tone="error" className="mb-0 mt-3">
          {error}
        </Alert>
      )}
      <Alert tone="warning" className="mb-0 mt-3">
        {warning ?? (
          <>
            We can&apos;t recover it for you, so if you lose both your password and
            this key, your encrypted data is gone for good. No one can read it.
          </>
        )}
      </Alert>

      <div
        // Monospace + wide letter spacing so the grouped key is easy to
        // transcribe. The key arrives already grouped into hyphen-separated
        // blocks from the crypto layer (encodeRecoveryKey); render it verbatim
        // so what's shown matches exactly what's copied to the clipboard.
        className="my-4 rounded-md border border-line-strong bg-surface p-4 font-mono text-sm tracking-wider text-ink"
        data-testid="recovery-key-display"
      >
        {recoveryKey}
      </div>

      <div className="mb-4 flex flex-wrap items-center gap-3">
        <button type="button" className={btnSecondaryClass} onClick={onCopyClick}>
          Copy recovery key
        </button>
        {/* role="status" (polite live region) so assistive tech hears the
            result of the copy the user just triggered — success or failure —
            not only sighted users via the visible text. The button's own
            label is deliberately unchanged (unlike SyncDetailsPopover's
            onCopy): re-labelling the control the user just pressed isn't a
            reliable substitute for announcing it.
            The region itself is always in the DOM (empty when idle); only
            its text is conditional. Live regions are registered by
            assistive tech when they enter the accessibility tree — content
            that arrives in the same commit as the region is routinely
            dropped by screen readers, so a region created and filled in the
            same render risks never being announced. */}
        <Muted as="span" role="status" className="text-xs">
          {copyResult === 'copied'
            ? 'Copied to clipboard.'
            : copyResult === 'failed'
              ? "Couldn't copy. Please copy the key above manually."
              : ''}
        </Muted>
      </div>

      <Checkbox
        isSelected={saved}
        onChange={setSaved}
        className="group flex cursor-pointer items-start gap-2 text-sm text-ink"
      >
        <span
          aria-hidden="true"
          className="mt-0.5 flex size-5 flex-none items-center justify-center rounded border border-input-line bg-surface text-accent-ink group-data-[selected]:border-accent group-data-[selected]:bg-accent group-data-[focus-visible]:ring-2 group-data-[focus-visible]:ring-ring group-data-[focus-visible]:ring-offset-2"
        >
          <svg viewBox="0 0 16 16" className="size-3.5 opacity-0 group-data-[selected]:opacity-100" fill="none" stroke="currentColor" strokeWidth={2.5}>
            <path d="M3 8.5l3 3 7-7" strokeLinecap="round" strokeLinejoin="round" />
          </svg>
        </span>
        <span>{savedLabel}</span>
      </Checkbox>

      {/* Left-aligned, primary first ("Modals" in docs/ui-conventions.md). */}
      <div className="mt-5 flex flex-wrap items-center gap-3">
        <button
          type="button"
          className={btnPrimaryClass}
          onClick={onConfirmed}
          disabled={!saved || confirmDisabled}
        >
          {confirmLabel}
        </button>
        <button type="button" className={btnSecondaryClass} onClick={onDismiss}>
          Cancel
        </button>
      </div>
    </Modal>
  );
};
