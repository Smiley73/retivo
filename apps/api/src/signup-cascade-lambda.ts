/**
 * Stream-triggered cascade Lambda for the signup-approval gate.
 *
 * Trigger: DynamoDB stream on the SignupApproval table (NEW_AND_OLD_IMAGES).
 * Action: for each REMOVE event whose row was deleted by DynamoDB TTL
 * (the only legitimate trigger for this Lambda — owner-initiated decline
 * also deletes the row but the request handler already did the cascade
 * synchronously), look up the still-pending user and delete the user +
 * credential + email-reservation in a TransactWrite. Idempotent: if the
 * user has already been deleted (replay, or the api beat us to it), the
 * conditional Delete is a no-op and we report success.
 *
 * Standalone — no Nest bootstrap. The cascade is small enough that the
 * extra modules are not worth the cold-start cost.
 */
import 'reflect-metadata';
import type {
  Context,
  DynamoDBBatchResponse,
  DynamoDBRecord,
  DynamoDBStreamEvent,
} from 'aws-lambda';
import {
  DynamoDBClient,
  TransactionCanceledException,
} from '@aws-sdk/client-dynamodb';
import {
  DynamoDBDocumentClient,
  GetCommand,
  PutCommand,
  TransactWriteCommand,
} from '@aws-sdk/lib-dynamodb';
import { randomUUID } from 'node:crypto';

interface UserRow {
  userId: string;
  emailLowercase: string;
  householdId: string;
  approvalStatus?: 'auto_approved' | 'pending' | 'approved' | 'declined';
}

interface CascadeEnv {
  userTable: string;
  credentialTable: string;
  emailReservationTable: string;
  authEventTable: string;
  region: string;
}

let cachedDoc: DynamoDBDocumentClient | undefined;
let cachedEnv: CascadeEnv | undefined;

function getEnv(): CascadeEnv {
  if (cachedEnv) return cachedEnv;
  const required = (key: string): string => {
    const v = process.env[key];
    if (!v) {
      throw new Error(`Missing required env var: ${key}`);
    }
    return v;
  };
  cachedEnv = {
    userTable: required('TABLE_USER'),
    credentialTable: required('TABLE_CREDENTIAL'),
    emailReservationTable: required('TABLE_EMAIL_RESERVATION'),
    authEventTable: required('TABLE_AUTH_EVENT'),
    region: process.env.AWS_REGION ?? 'us-east-1',
  };
  return cachedEnv;
}

function getDoc(): DynamoDBDocumentClient {
  if (cachedDoc) return cachedDoc;
  const env = getEnv();
  const client = new DynamoDBClient({ region: env.region });
  cachedDoc = DynamoDBDocumentClient.from(client);
  return cachedDoc;
}

/**
 * Returns true iff this REMOVE record was generated by DynamoDB TTL
 * (rather than an explicit DeleteItem from the api). TTL deletes carry
 * `userIdentity = { type: "Service", principalId: "dynamodb.amazonaws.com" }`
 * — the documented signal for this exact use case.
 */
function isTtlDelete(record: DynamoDBRecord): boolean {
  const userIdentity = (record as DynamoDBRecord & {
    userIdentity?: { type?: string; principalId?: string };
  }).userIdentity;
  return (
    userIdentity?.type === 'Service' &&
    userIdentity?.principalId === 'dynamodb.amazonaws.com'
  );
}

function extractUserId(record: DynamoDBRecord): string | null {
  const oldImage = record.dynamodb?.OldImage;
  const userId = oldImage?.userId?.S;
  return typeof userId === 'string' && userId.length > 0 ? userId : null;
}

async function cascadeDeleteUser(userId: string): Promise<void> {
  const env = getEnv();
  const doc = getDoc();

  const userRes = await doc.send(
    new GetCommand({ TableName: env.userTable, Key: { userId } }),
  );
  const user = userRes.Item as UserRow | undefined;
  if (!user) {
    // Already cleaned up by the api (decline path) or a prior replay.
    return;
  }

  // Refuse to sweep a user who's already been approved between when the
  // TTL fired and the cascade ran. The conditional Delete below catches
  // this too; bailing here saves an unconditional read of the credential
  // row.
  const status = user.approvalStatus ?? null;
  if (status !== 'pending' && status !== 'declined') return;

  try {
    await doc.send(
      new TransactWriteCommand({
        TransactItems: [
          {
            Delete: {
              TableName: env.emailReservationTable,
              Key: { emailLowercase: user.emailLowercase },
              ConditionExpression: 'userId = :u',
              ExpressionAttributeValues: { ':u': user.userId },
            },
          },
          {
            Delete: {
              TableName: env.userTable,
              Key: { userId: user.userId },
              ConditionExpression:
                'attribute_exists(userId) AND (approvalStatus = :pending OR approvalStatus = :declined)',
              ExpressionAttributeValues: {
                ':pending': 'pending',
                ':declined': 'declined',
              },
            },
          },
          {
            Delete: {
              TableName: env.credentialTable,
              Key: { userId: user.userId },
            },
          },
        ],
      }),
    );
  } catch (err) {
    if (err instanceof TransactionCanceledException) {
      // Lost the race — user got approved or another replay cascaded
      // first. Both benign; the row reaches its final state via the
      // winning path.
      return;
    }
    throw err;
  }

  // Audit. Best-effort — losing the audit row doesn't justify failing
  // the whole batch (which would replay the cascade endlessly).
  try {
    const nowSec = Math.floor(Date.now() / 1000);
    await doc.send(
      new PutCommand({
        TableName: env.authEventTable,
        Item: {
          userId,
          eventId: `${Date.now()}-${randomUUID()}`,
          eventType: 'signup_approval_expired',
          ip: null,
          userAgent: null,
          metadata: { householdId: user.householdId },
          createdAt: new Date().toISOString(),
          // 1-year TTL matches AuthEventsRepository.
          expiresAt: nowSec + 365 * 24 * 60 * 60,
        },
      }),
    );
  } catch (err) {
    console.warn(
      `signup-cascade: audit write failed for ${userId}: ${err instanceof Error ? err.message : String(err)}`,
    );
  }
}

export const handler = async (
  event: DynamoDBStreamEvent,
  _context: Context,
): Promise<DynamoDBBatchResponse> => {
  const failures: DynamoDBBatchResponse['batchItemFailures'] = [];
  for (const record of event.Records ?? []) {
    if (record.eventName !== 'REMOVE') continue;
    if (!isTtlDelete(record)) continue;

    const userId = extractUserId(record);
    if (!userId) continue;

    try {
      await cascadeDeleteUser(userId);
    } catch (err) {
      console.error(
        `signup-cascade: cascade failed for ${userId}: ${err instanceof Error ? err.stack ?? err.message : String(err)}`,
      );
      // Surface as a partial-batch failure — the EventSourceMapping is
      // configured with bisectBatchOnFunctionError so this just retries
      // the offending record, not the whole batch.
      const sequenceNumber = record.dynamodb?.SequenceNumber;
      if (sequenceNumber) {
        failures.push({ itemIdentifier: sequenceNumber });
      }
    }
  }
  return { batchItemFailures: failures };
};
